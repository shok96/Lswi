use crate::keys;
use rdev::Key;

pub fn key_to_vk(key: Key) -> u16 {
    match key {
        Key::ShiftLeft | Key::ShiftRight => keys::VK_LSHIFT,
        Key::ControlLeft | Key::ControlRight => keys::VK_LCONTROL,
        Key::Alt | Key::AltGr => keys::VK_LMENU,
        Key::MetaLeft | Key::MetaRight => keys::VK_LWIN,
        Key::Pause => keys::VK_PAUSE,
        Key::CapsLock => keys::VK_CAPITAL,
        Key::ScrollLock => keys::VK_SCROLL,
        Key::NumLock => keys::VK_NUMLOCK,
        Key::PrintScreen => keys::VK_SNAPSHOT,
        Key::Space => keys::VK_SPACE,
        Key::Tab => keys::VK_TAB,
        Key::Return | Key::KpReturn => keys::VK_RETURN,
        Key::Escape => keys::VK_ESCAPE,
        Key::Backspace => keys::VK_BACK,
        Key::Insert => keys::VK_INSERT,
        Key::Delete | Key::KpDelete => keys::VK_DELETE,
        Key::Home => keys::VK_HOME,
        Key::End => keys::VK_END,
        Key::PageUp => keys::VK_PRIOR,
        Key::PageDown => keys::VK_NEXT,
        Key::LeftArrow => keys::VK_LEFT,
        Key::RightArrow => keys::VK_RIGHT,
        Key::UpArrow => keys::VK_UP,
        Key::DownArrow => keys::VK_DOWN,
        Key::F1 => keys::VK_F1,
        Key::F2 => keys::VK_F1 + 1,
        Key::F3 => keys::VK_F1 + 2,
        Key::F4 => keys::VK_F1 + 3,
        Key::F5 => keys::VK_F1 + 4,
        Key::F6 => keys::VK_F1 + 5,
        Key::F7 => keys::VK_F1 + 6,
        Key::F8 => keys::VK_F1 + 7,
        Key::F9 => keys::VK_F1 + 8,
        Key::F10 => keys::VK_F1 + 9,
        Key::F11 => keys::VK_F1 + 10,
        Key::F12 => keys::VK_F12,
        Key::F13 => keys::VK_F12 + 1,
        Key::F14 => keys::VK_F12 + 2,
        Key::F15 => keys::VK_F12 + 3,
        Key::F16 => keys::VK_F12 + 4,
        Key::F17 => keys::VK_F12 + 5,
        Key::F18 => keys::VK_F12 + 6,
        Key::F19 => keys::VK_F12 + 7,
        Key::F20 => keys::VK_F12 + 8,
        Key::F21 => keys::VK_F12 + 9,
        Key::F22 => keys::VK_F12 + 10,
        Key::F23 => keys::VK_F12 + 11,
        Key::F24 => keys::VK_F24,
        Key::Num0 | Key::Kp0 => 0x30,
        Key::Num1 | Key::Kp1 => 0x31,
        Key::Num2 | Key::Kp2 => 0x32,
        Key::Num3 | Key::Kp3 => 0x33,
        Key::Num4 | Key::Kp4 => 0x34,
        Key::Num5 | Key::Kp5 => 0x35,
        Key::Num6 | Key::Kp6 => 0x36,
        Key::Num7 | Key::Kp7 => 0x37,
        Key::Num8 | Key::Kp8 => 0x38,
        Key::Num9 | Key::Kp9 => 0x39,
        Key::KeyA => 0x41,
        Key::KeyB => 0x42,
        Key::KeyC => 0x43,
        Key::KeyD => 0x44,
        Key::KeyE => 0x45,
        Key::KeyF => 0x46,
        Key::KeyG => 0x47,
        Key::KeyH => 0x48,
        Key::KeyI => 0x49,
        Key::KeyJ => 0x4A,
        Key::KeyK => 0x4B,
        Key::KeyL => 0x4C,
        Key::KeyM => 0x4D,
        Key::KeyN => 0x4E,
        Key::KeyO => 0x4F,
        Key::KeyP => 0x50,
        Key::KeyQ => 0x51,
        Key::KeyR => 0x52,
        Key::KeyS => 0x53,
        Key::KeyT => 0x54,
        Key::KeyU => 0x55,
        Key::KeyV => 0x56,
        Key::KeyW => 0x57,
        Key::KeyX => 0x58,
        Key::KeyY => 0x59,
        Key::KeyZ => 0x5A,
        Key::SemiColon => keys::VK_OEM_1,
        Key::Equal => keys::VK_OEM_PLUS,
        Key::Comma => keys::VK_OEM_COMMA,
        Key::Minus | Key::KpMinus => keys::VK_OEM_MINUS,
        Key::Dot => keys::VK_OEM_PERIOD,
        Key::Slash | Key::KpDivide => keys::VK_OEM_2,
        Key::BackQuote => keys::VK_OEM_3,
        Key::LeftBracket => keys::VK_OEM_4,
        Key::BackSlash | Key::IntlBackslash => keys::VK_OEM_5,
        Key::RightBracket => keys::VK_OEM_6,
        Key::Quote => keys::VK_OEM_7,
        Key::Unknown(code) => code as u16,
        _ => 0,
    }
}
